import '../models/guide.dart';
import '../models/guide_procedure.dart';

const _evidence = GuideEvidence(
  sourceKey: 'sokrat-re',
  locator: '§ 3.10 · PDF с. 51–52; § 3.7 · PDF с. 34',
);

/// First method, beginning at the closed end; movement by manual override.
List<ProcedureStep> sokratTravelSteps(GuideIllustration controls) {
  ProcedureStep step({
    required String title,
    required String action,
    required String expected,
    String? control,
    String? hold,
  }) => ProcedureStep(
    title: title,
    action: action,
    expectedResult: expected,
    control: control,
    hold: hold,
    illustration: controls,
    evidence: const [_evidence],
  );

  return [
    step(
      title: 'Местное управление и закрытое положение',
      action:
          'Переведите блок в режим «Местный». При необходимости ручным дублёром установите арматуру в крайнее положение «Закрыто».',
      control: 'Рукоятка №2 · выбор режима; ручной дублёр привода',
      expected:
          'Горит индикатор «МУ/ДУ», в зоне источника команд показано «МПУ»; арматура находится в требуемом закрытом положении.',
    ),
    step(
      title: 'Вход в калибровку закрытия',
      action: 'Кратковременно поверните рукоятку №2 к КЛБ/ПРОГ и отпустите.',
      control: 'Рукоятка №2 · КЛБ/ПРОГ',
      hold: '0,2…2 секунды, затем отпустить',
      expected:
          'На индикаторе появилась надпись «КАЛИБРОВКА». Значение положения зависит от предыдущей калибровки.',
    ),
    step(
      title: 'Выбор закрытого положения',
      action: 'Поверните рукоятку №1 в положение ЗАКР.',
      control: 'Рукоятка №1 · ЗАКР',
      expected: 'На дисплее отображается «КАЛИБР:КВЗ».',
    ),
    step(
      title: 'Запись закрытого положения',
      action:
          'Поверните и удерживайте рукоятку №3 в положении ВВОД/СТОП до появления показания и индикатора закрытия.',
      control: 'Рукоятка №3 · ВВОД/СТОП',
      hold: 'До показания 0% и индикатора «ЗАКРЫТО»',
      expected:
          'Показано 0% и горит индикатор «ЗАКРЫТО»: блок зафиксировал закрытое положение.',
    ),
    step(
      title: 'Установка открытого положения',
      action:
          'Ручным дублёром переместите арматуру и установите требуемое крайнее положение «Открыто».',
      control: 'Ручной дублёр привода',
      expected:
          'Арматура установлена в требуемое открытое положение; показание до записи не обязано быть 100%.',
    ),
    step(
      title: 'Вход в калибровку открытия',
      action: 'Кратковременно поверните рукоятку №2 к КЛБ/ПРОГ и отпустите.',
      control: 'Рукоятка №2 · КЛБ/ПРОГ',
      hold: '0,2…2 секунды, затем отпустить',
      expected:
          'На индикаторе появилась надпись «КАЛИБРОВКА». Значение положения зависит от фактического положения и калибровки.',
    ),
    step(
      title: 'Выбор открытого положения',
      action: 'Поверните рукоятку №1 в положение ОТКР.',
      control: 'Рукоятка №1 · ОТКР',
      expected: 'На дисплее отображается «КАЛИБР:КВО».',
    ),
    step(
      title: 'Запись открытого положения',
      action:
          'Поверните и удерживайте рукоятку №3 в положении ВВОД/СТОП до появления показания и индикатора открытия.',
      control: 'Рукоятка №3 · ВВОД/СТОП',
      hold: 'До показания 100% и индикатора «ОТКРЫТО»',
      expected:
          'Показано 100% и горит индикатор «ОТКРЫТО»: блок зафиксировал открытое положение.',
    ),
  ];
}
